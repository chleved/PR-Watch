#!/usr/bin/env python3
"""Generate Widget.ini for the PR Watch skin.

Rainmeter has no loops, so the row meters are written out by this script.
Usage: python make_skin.py [--rows 8] [--width 380] [--out Widget.ini]

--rows is the most rows shown at once; the skin is only as tall as the PRs it has
(up to that many) and scrolls with the mouse wheel beyond it.
"""
import argparse
import sys

MARGIN = 8
ROW_H = 68
GAP = 4
MAX_ROWS = 20  # must not exceed the rows fetch_prs.py pads prs.inc to
MIN_WIDTH = 380
PANEL_RGB = "16,19,26"
ROW_RGB = "25,27,35"
CYAN = "0,240,255"
PURPLE = "208,188,255"
ORANGE = "255,171,64"
TEXT = "225,226,236"

# status chip, messages chip, commits chip, releases chip: (x inside the row, width)
CHIP_STATUS = (14, 92)
CHIP_MSGS = (110, 36)
CHIP_COMMITS = (150, 100)
CHIP_RELEASES = (254, 100)
CHIP_Y, CHIP_H = 46, 16

ICON = 16
BADGE_PAD = "6,2,6,2"  # left, top, right, bottom padding of the PR# and age badges

SCROLL = ('[!SetVariable Offset "[{m}]"][!WriteKeyValue Variables Offset "[{m}]" "#@#state.inc"]'
          '[!UpdateMeasure *][!UpdateMeter *][!Redraw]')
SCROLL_UP = SCROLL.format(m="MOffUp")
SCROLL_DOWN = SCROLL.format(m="MOffDown")


def section(name, items):
    lines = [f"[{name}]"] + [f"{k}={v}" for k, v in items]
    return "\n".join(lines) + "\n"


def build(rows, width):
    rw = width - 2 * MARGIN
    out = []

    out.append(section("Rainmeter", [
        ("Update", "1000"),
        ("AccurateText", "1"),
        ("ContextTitle", "Fetch now"),
        ("ContextAction", '[!CommandMeasure "MFetch" "Run" "#UpdaterConfig#"]'),
        ("ContextTitle2", "Edit PR list"),
        ("ContextAction2", '["#@#fetcher\\prs.txt"]'),
    ]))
    out.append(section("Metadata", [
        ("Name", "PR Watch"),
        ("Information", "Status of a list of GitHub pull requests. Generated by tools/make_skin.py"),
        ("Version", "1.1"),
    ]))
    out.append(section("Variables", [
        ("Rows", str(rows)),
        ("Step", "1"),
        ("UpdaterConfig", "PRWidget\\Updater"),
        ("FontMono", "Consolas"),
        ("FontSans", "Segoe UI"),
        ("@Include", "#@#fetcher\\data\\prs.inc"),
        ("@Include2", "#@#state.inc"),
    ]))

    # ---- measures: scroll position, panel height, then a few per row ----
    out.append(section("MOffMax", [("Measure", "Calc"), ("Formula", "Max(0,#Count#-#Rows#)")]))
    out.append(section("MOffset", [("Measure", "Calc"),
                                   ("Formula", "Clamp(#Offset#,0,MOffMax)"),
                                   ("DynamicVariables", "1")]))
    out.append(section("MOffUp", [("Measure", "Calc"),
                                  ("Formula", "Clamp(#Offset#-#Step#,0,MOffMax)"),
                                  ("DynamicVariables", "1")]))
    out.append(section("MOffDown", [("Measure", "Calc"),
                                    ("Formula", "Clamp(#Offset#+#Step#,0,MOffMax)"),
                                    ("DynamicVariables", "1")]))
    # panel height follows the number of visible rows: margins + n rows + gaps between them
    out.append(section("MShown", [("Measure", "Calc"), ("Formula", f"Clamp(#Count#,0,#Rows#)")]))
    out.append(section("MPanelH", [("Measure", "Calc"),
                                   ("Formula", f"{2 * MARGIN - GAP}+MShown*{ROW_H + GAP}")]))
    out.append(section("MPanelIn", [("Measure", "Calc"), ("Formula", "MPanelH-2")]))
    out.append(section("MPanelHide", [
        ("Measure", "Calc"),
        ("Formula", "(#Count# <= 0) ? 1 : 0"),
        ("IfCondition", "#Count# <= 0"),
        ("IfTrueAction", "[!Hide]"),
        ("IfFalseAction", "[!Show]"),
    ]))
    out.append(section("MNow", [("Measure", "Time"), ("Format", "%s")]))
    for r in range(1, rows + 1):
        idx = f"[&MIdx{r}:0]"
        out.append(section(f"MIdx{r}", [("Measure", "Calc"), ("Formula", f"MOffset+{r}")]))
        # 1 = hide: the row is past the last PR
        out.append(section(f"MH{r}", [("Measure", "Calc"),
                                      ("Formula", f"(MIdx{r} > #Count#) ? 1 : 0")]))
        # hide a badge/icon when its row is hidden or the PR has no value for it
        for tag, var in (("I", "IconHide"), ("P", "PrHide"), ("A", "AgeHide")):
            out.append(section(f"MH{tag}{r}", [
                ("Measure", "Calc"),
                ("Formula", f"((MH{r} + [#{var}{idx}]) > 0) ? 1 : 0"),
                ("DynamicVariables", "1")]))
        out.append(section(f"MC{r}", [("Measure", "Calc"),
                                      ("Formula", f"[#Chip{idx}] * 36"),
                                      ("DynamicVariables", "1")]))
        out.append(section(f"MM{r}", [("Measure", "Calc"),
                                      ("Formula", f"[#Chip{idx}] * 255"),
                                      ("DynamicVariables", "1")]))

    # ---- meters ----
    scroll = [("MouseScrollUpAction", SCROLL_UP), ("MouseScrollDownAction", SCROLL_DOWN)]
    out.append(section("Panel", [
        ("Meter", "Shape"), ("X", "0"), ("Y", "0"), ("W", str(width)), ("H", "[MPanelH:0]"),
        ("DynamicVariables", "1"),
        ("Hidden", "[MPanelHide:0]"),
        ("Shape", f"Rectangle 1,1,{width - 2},[MPanelIn:0],10 | Fill Color {PANEL_RGB},215"
                  f" | StrokeWidth 1 | Stroke Color 59,73,75,140"),
    ] + scroll))

    for r in range(1, rows + 1):
        y0 = MARGIN + (r - 1) * (ROW_H + GAP)
        idx = f"[&MIdx{r}:0]"  # :0 = whole number, the only decimals form the docs guarantee
        color = f"[#Color{idx}]"
        hide = f"[MH{r}:0]"
        sx, sw = CHIP_STATUS
        mx, mw = CHIP_MSGS
        cx, cw = CHIP_COMMITS
        lx, lw = CHIP_RELEASES

        def chip(x, w):
            return f"Rectangle {x},{CHIP_Y},{w},{CHIP_H},3"

        click = (
            f'["[#Url{idx}]"]'
            f'[!WriteKeyValue Seen "[#Key{idx}]" "[MNow]" "#@#state.inc"]'
            f'[!SetVariable "Msgs{idx}" "0"]'
            f'[!SetVariable "MsgColor{idx}" "110,115,125"]'
            f'[!SetVariable "MsgBg{idx}" "75,80,90,35"]'
            f'[!UpdateMeasure *][!UpdateMeter *][!Redraw]'
        )

        out.append(section(f"Row{r}", [
            ("Meter", "Shape"), ("X", str(MARGIN)), ("Y", str(y0)),
            ("W", str(rw)), ("H", str(ROW_H)), ("DynamicVariables", "1"),
            ("Hidden", hide),
            ("Shape", f"Rectangle 0,0,{rw},{ROW_H},6 | Fill Color {ROW_RGB},255 | StrokeWidth 0"),
            ("Shape2", f"Rectangle 0,0,3,{ROW_H},1.5 | Fill Color {color},255 | StrokeWidth 0"),
            ("Shape3", f"{chip(sx, sw)} | Fill Color {color},40 | StrokeWidth 0"),
            ("Shape4", f"{chip(cx, cw)} | Fill Color {CYAN},[MC{r}:0] | StrokeWidth 0"),
            ("Shape5", f"{chip(lx, lw)} | Fill Color {PURPLE},[MC{r}:0] | StrokeWidth 0"),
            ("Shape6", f"{chip(mx, mw)} | Fill Color [#MsgBg{idx}] | StrokeWidth 0"),
            ("LeftMouseUpAction", click),
        ] + scroll))

        def text(name, x, y, value, size, color, font="#FontMono#", weight="400",
                 align=None, w=None, h=None, hidden=hide, extra=()):
            items = [("Meter", "String"), ("X", str(x)), ("Y", str(y)),
                     ("DynamicVariables", "1"), ("Hidden", hidden),
                     ("FontFace", font), ("FontSize", str(size)),
                     ("FontWeight", weight), ("FontColor", color), ("AntiAlias", "1"),
                     ("Text", value)]
            if align:
                items.append(("StringAlign", align))
            if w:
                items += [("W", str(w)), ("H", str(h)), ("ClipString", "1")]
            items += list(extra)
            out.append(section(f"{name}{r}", items))

        # top line: icon | repo name | PR# badge ............ age badge
        icon_x = MARGIN + 14
        out.append(section(f"Icon{r}", [
            ("Meter", "Image"), ("X", str(icon_x)), ("Y", str(y0 + 6)),
            ("W", str(ICON)), ("H", str(ICON)), ("PreserveAspectRatio", "1"),
            ("DynamicVariables", "1"), ("Hidden", f"[MHI{r}:0]"),
            ("ImageName", f"[#Icon{idx}]"),
        ]))
        text("Ref", icon_x + ICON + 6, y0 + 8, f"[#Ref{idx}]", 10, f"{CYAN},255")
        # X=6R puts the badge 6px to the right of the repo name, wherever that ends
        text("Pr", "6R", y0 + 6, f"[#Pr{idx}]", 8, f"{ROW_RGB},255", weight="700",
             hidden=f"[MHP{r}:0]",
             extra=[("SolidColor", f"{PURPLE},255"), ("Padding", BADGE_PAD)])
        text("Age", MARGIN + rw - 10, y0 + 6, f"[#Age{idx}]", 8, f"{ROW_RGB},255",
             weight="700", align="Right", hidden=f"[MHA{r}:0]",
             extra=[("SolidColor", f"{ORANGE},255"), ("Padding", BADGE_PAD)])

        text("Ttl", MARGIN + 14, y0 + 25, f"[#Title{idx}]", 10, f"{TEXT},255",
             font="#FontSans#", weight="600", w=rw - 28, h=16)
        text("Stat", MARGIN + sx + sw // 2, y0 + CHIP_Y + 1, f"[#Status{idx}]", 10,
             f"{color},255", weight="700", align="Center")
        text("Msg", MARGIN + mx + mw // 2, y0 + CHIP_Y + 2, f"[#Msgs{idx}]", 9,
             f"[#MsgColor{idx}],[MM{r}:0]", weight="700", align="Center")
        text("Cmt", MARGIN + cx + cw // 2, y0 + CHIP_Y + 2, f"[#Commits{idx}]", 9,
             f"{CYAN},255", align="Center")
        text("Rel", MARGIN + lx + lw // 2, y0 + CHIP_Y + 2, f"[#Rels{idx}]", 9,
             f"{PURPLE},255", align="Center")

    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=8)
    ap.add_argument("--width", type=int, default=MIN_WIDTH)
    ap.add_argument("--out", default="Widget.ini")
    args = ap.parse_args()
    if not 1 <= args.rows <= MAX_ROWS:
        print(f"--rows must be 1..{MAX_ROWS}", file=sys.stderr)
        return 2
    if args.width < MIN_WIDTH:
        print(f"--width must be at least {MIN_WIDTH} (the chips need the room)", file=sys.stderr)
        return 2
    with open(args.out, "w", encoding="ascii", newline="\r\n") as f:
        f.write(build(args.rows, args.width))
    print(f"wrote {args.out}: up to {args.rows} rows, {args.width}px wide")
    return 0


if __name__ == "__main__":
    sys.exit(main())